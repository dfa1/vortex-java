package io.github.dfa1.vortex.fuzz;

import java.io.IOException;
import java.lang.foreign.Arena;
import java.nio.ByteBuffer;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;

import com.code_intelligence.jazzer.junit.FuzzTest;
import io.github.dfa1.vortex.core.error.VortexException;
import io.github.dfa1.vortex.core.model.ColumnName;
import io.github.dfa1.vortex.core.model.DType;
import io.github.dfa1.vortex.reader.Chunk;
import io.github.dfa1.vortex.reader.RowFilter;
import io.github.dfa1.vortex.reader.ScanIterator;
import io.github.dfa1.vortex.reader.ScanOptions;
import io.github.dfa1.vortex.reader.VortexReader;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.io.TempDir;

/// Coverage-guided fuzzing of the reader (ADR 0020). The reader's security contract requires every
/// malformed input to surface as a [VortexException] — anything else escaping a target (an [Error],
/// a raw `IndexOutOfBoundsException`, a FlatBuffer/Protobuf parser exception) is a real finding, so
/// the fuzzer's pass/fail oracle is simply "no other throwable escapes".
///
/// There is no `VortexReader.open(byte[])`: the public API memory-maps a real file, so the fuzzer
/// bytes are written to a temp file and fed through the actual [VortexReader#open(Path)] entry
/// point — exactly the path a malformed file on disk would hit.
///
/// Every target replays its saved inputs in a routine `./mvnw test`; run with `JAZZER_FUZZ=1` to
/// explore new inputs instead (see AGENTS.md).
@Tag("fuzz")
class VortexReaderFuzzTest {

    /// Length of the filter-choice header in front of the file in
    /// [#filterMalformedFile(byte[])]'s inputs.
    static final int FILTER_HEADER_BYTES = 16;

    /// Length of the blob-length header in front of [#parseMetadataBlobs(byte[])]'s inputs.
    static final int BLOB_HEADER_BYTES = 4;

    // @FuzzTest defaults to PER_TEST lifecycle: the test instance — and therefore this injected
    // temp directory — is created once and reused across every fuzzing execution.
    @TempDir
    Path tempDir;

    private Path fuzzFile;

    @BeforeEach
    void setUp() {
        fuzzFile = tempDir.resolve("fuzz.vortex");
    }

    /// The open path alone: trailer, postscript, footer, layout and dtype. Fastest target, so it
    /// explores the file-level metadata deepest.
    @FuzzTest
    void openMalformedFile(byte[] data) throws IOException {
        // Given
        Files.write(fuzzFile, data);

        // When / Then — anything but a VortexException escaping is a finding
        try (var _ = VortexReader.open(fuzzFile)) {
            // Successfully opened: fine. The security contract only requires that MALFORMED input
            // fails as VortexException, not that every fuzzer-generated byte string is rejected.
        } catch (VortexException _) {
            // Malformed input correctly rejected per the reader's security contract.
        }
    }

    /// Past the open into the data: file statistics, then every value of every chunk through
    /// [ArrayWalker], so the encoding decoders and the `Lazy*` arrays see fuzzed input. Seeded with
    /// one small file per encoding ([SeedCorpusGenerator]).
    @FuzzTest
    void scanMalformedFile(byte[] data) throws IOException {
        // Given
        Files.write(fuzzFile, data);

        // When / Then — anything but a VortexException escaping is a finding
        try (VortexReader reader = VortexReader.open(fuzzFile)) {
            reader.columnStats();
            scan(reader, ScanOptions.all());
        } catch (VortexException _) {
            // Malformed input correctly rejected per the reader's security contract.
        }
    }

    /// The scan again, filtered: zone-map tables are parsed and chunks pruned against a filter the
    /// fuzzer chooses. The input is a [#FILTER_HEADER_BYTES]-byte header of filter choices followed
    /// by the file, rather than numbers drawn from a `FuzzedDataProvider`, which takes them from the
    /// end of the input, where the file's trailer is: seeds stay valid files.
    @FuzzTest
    void filterMalformedFile(byte[] data) throws IOException {
        if (data.length < FILTER_HEADER_BYTES) {
            return;
        }
        // Given
        ByteBuffer header = ByteBuffer.wrap(data, 0, FILTER_HEADER_BYTES);
        Files.write(fuzzFile, Arrays.copyOfRange(data, FILTER_HEADER_BYTES, data.length));

        // When / Then — anything but a VortexException escaping is a finding
        try (VortexReader reader = VortexReader.open(fuzzFile)) {
            if (reader.dtype() instanceof DType.Struct schema && !schema.fieldNames().isEmpty()) {
                int column = Math.floorMod(header.getInt(), schema.fieldNames().size());
                RowFilter filter = filter(schema.fieldNames().get(column), schema.fieldTypes().get(column),
                        header.get(), header.getLong());
                scan(reader, ScanOptions.all().withFilter(filter));
            }
        } catch (VortexException _) {
            // Malformed input correctly rejected per the reader's security contract.
        }
    }

    /// `PostscriptParser.parseBlobs` reached directly: the input is the footer, layout and dtype
    /// FlatBuffers themselves (behind a 4-byte header of the first two lengths), wrapped here in a
    /// valid postscript and trailer, so every mutation lands in the metadata parse instead of being
    /// spent breaking the file framing [#openMalformedFile(byte[])] has to get past first. Built
    /// through the public API: no access seam into the reader's package.
    @FuzzTest
    void parseMetadataBlobs(byte[] data) throws IOException {
        // Given
        if (data.length < BLOB_HEADER_BYTES) {
            return;
        }
        ByteBuffer header = ByteBuffer.wrap(data, 0, BLOB_HEADER_BYTES);
        int footerLength = Short.toUnsignedInt(header.getShort());
        int layoutLength = Short.toUnsignedInt(header.getShort());
        int dtypeLength = data.length - BLOB_HEADER_BYTES - footerLength - layoutLength;
        if (dtypeLength < 0) {
            return;
        }
        Files.write(fuzzFile, MetadataBlobs.assemble(data, BLOB_HEADER_BYTES, footerLength, layoutLength, dtypeLength));

        // When / Then — anything but a VortexException escaping is a finding
        try (var _ = VortexReader.open(fuzzFile)) {
            // Parsed: fine, as for openMalformedFile.
        } catch (VortexException _) {
            // Malformed input correctly rejected per the reader's security contract.
        }
    }

    private static void scan(VortexReader reader, ScanOptions options) {
        try (ScanIterator chunks = reader.scan(options)) {
            while (chunks.hasNext()) {
                try (Chunk chunk = chunks.next(); Arena arena = Arena.ofConfined()) {
                    ArrayWalker.walk(chunk, arena);
                }
            }
        }
    }

    /// A predicate on `column` with a value of the type its dtype compares against: a mismatched
    /// value is a caller error, not malformed input, so it would only produce false findings.
    private static RowFilter filter(ColumnName column, DType dtype, byte kind, long bits) {
        Comparable<?> value = switch (dtype) {
            case DType.Primitive p when p.ptype().isFloating() -> Double.longBitsToDouble(bits);
            case DType.Primitive _ -> bits;
            case DType.Utf8 _ -> Long.toString(bits);
            case DType.Bool _ -> (bits & 1) != 0;
            default -> null;
        };
        if (value == null) {
            return (kind & 1) == 0 ? RowFilter.isNull(column) : RowFilter.isNotNull(column);
        }
        return switch (Math.floorMod(kind, 8)) {
            case 0 -> RowFilter.eq(column, value);
            case 1 -> RowFilter.neq(column, value);
            case 2 -> RowFilter.gt(column, value);
            case 3 -> RowFilter.gte(column, value);
            case 4 -> RowFilter.lt(column, value);
            case 5 -> RowFilter.lte(column, value);
            case 6 -> RowFilter.isNull(column);
            default -> RowFilter.isNotNull(column);
        };
    }
}
